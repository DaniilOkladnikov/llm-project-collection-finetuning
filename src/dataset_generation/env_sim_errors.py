class SimulationError(Exception):
    """Base class for all simulator errors."""
    def __init__(self, message: str, *, context: dict | None = None):
        super().__init__(message)
        self.context = context or {}

class JSONError(SimulationError): ...
class UnknownPositionError(SimulationError): ...
class MovingError(SimulationError): ...
class MovingToOccupiedLocError(SimulationError): ...
class WrongReleasePos(SimulationError): ...
class CloseGripperError(SimulationError): ...
